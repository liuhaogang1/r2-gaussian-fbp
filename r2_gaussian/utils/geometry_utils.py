"""Physical geometry shared by FBP initialization and Gaussian projection.

Detector arrays use [V, U]; volume arrays and positions use [X, Y, Z].
Projection functions receive the scene-normalized scanner from the dataset
reader, so detector lengths have already been multiplied by 2/max(sVoxel).
"""

import numpy as np


def reorder_tigre_detector_offset(offset_uv, order="vu"):
    """Reorder already row-flipped TIGRE detector offsets from UV or VU."""
    values = np.asarray(offset_uv, dtype=np.float32)
    if values.shape[-1:] != (2,) or not np.isfinite(values).all():
        raise ValueError("TIGRE detector offsets must be finite [...,2] values")
    if order == "uv":
        return values.copy()
    if order == "vu":
        return values[..., ::-1].copy()
    raise ValueError("TIGRE detector offset order must be 'uv' or 'vu'")


def tigre_detector_offset(offset, order="vu"):
    """Map physical detector [U,V] offsets to TIGRE's selected axis order.

    Projection rows are reversed before TIGRE reconstruction, so V changes
    sign. The local pytigre build uses VU order: [U,V] becomes [-V,U].
    """
    values = np.asarray(offset, dtype=np.float32)
    if values.shape != (2,) or not np.isfinite(values).all():
        raise ValueError("Detector offset must contain finite physical [U,V] values")
    uv_after_row_flip = np.asarray([values[0], -values[1]], dtype=np.float32)
    return reorder_tigre_detector_offset(uv_after_row_flip, order)


def parallel_detector_half_extents(scanner):
    """Return camera U/V half extents, not perspective field-of-view angles."""
    size = np.asarray(scanner["sDetector"], dtype=np.float64)
    if size.shape != (2,) or not np.isfinite(size).all() or np.any(size <= 0):
        raise ValueError("scanner.sDetector must contain positive finite [V, U] lengths")
    return float(size[1] / 2), float(size[0] / 2)


def parallel_projection_matrix(scanner):
    """Map camera coordinates to physical detector NDC, without pose shifts."""
    half_u, half_v = parallel_detector_half_extents(scanner)
    matrix = np.eye(4, dtype=np.float32)
    matrix[0, 0] = 1 / half_u
    matrix[1, 1] = 1 / half_v
    return matrix


def initialization_positions(indices, shape, scanner=None):
    """Map physical XYZ voxel centers into the Gaussian scene coordinates.

    Standalone volumes without scanner metadata retain the centered unit-cube
    convention. With metadata, preserve non-cubic bounds and offOrigin.
    """
    fractions = (np.asarray(indices, dtype=np.float32) + 0.5) / np.asarray(shape, dtype=np.float32)
    if scanner is None:
        return fractions * 2 - 1
    size = np.asarray(scanner["sVoxel"], dtype=np.float32)
    origin = np.asarray(scanner.get("offOrigin", [0, 0, 0]), dtype=np.float32)
    if size.shape != (3,) or not np.isfinite(size).all() or np.any(size <= 0):
        raise ValueError("scanner.sVoxel must contain positive finite XYZ lengths")
    if origin.shape != (3,) or not np.isfinite(origin).all():
        raise ValueError("scanner.offOrigin must contain finite XYZ coordinates")
    return (origin + (fractions - 0.5) * size) * (2 / float(size.max()))


def validate_physical_dataset(metadata):
    """Reject volumes generated by the removed virtual-detector mode."""
    if metadata.get("reconstruction", {}).get("coordinate_mode") == "gaussian":
        raise ValueError(
            "This dataset uses the removed Gaussian-compatible FBP geometry. "
            "Regenerate physical FBP and initialization in a new dataset directory; "
            "do not reuse its volumes with the physical Gaussian projector."
        )
